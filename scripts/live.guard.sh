#!/bin/sh
# live.guard.sh — confirmation gate for the live-WM test suite.
#
# The integration tests take over the running session for a few moments:
# they switch to a scratch tag, spawn real windows (Alacritty / Byobu)
# and rearrange frames, then tear everything down again. This guard
# warns the user first and waits for explicit confirmation:
#
#   1. primary: an xmessage dialog, spawnED via `polyframes spawn
#      --center` so it floats and centers on the focused frame. Buttons
#      Start (exit 0) / Abort (exit 2). The dialog runs under a wrapper
#      sh so its exit status lands in a temp file; the guard polls the
#      file for the user's choice (detached spawns lose exit codes).
#      Font is customizable: $POLYFRAMES_GUARD_FONT overrides; otherwise
#      the first available candidate (big Times bold / Courier bold) is
#      used, falling back to xmessage's tiny default only if the server
#      has none of them.
#   2. fallback (only when xmessage is absent): a transient $TERMINAL
#      spawned via `polyframes spawn --class Alacritty --float on` with
#      a press-any-key prompt; closing the window or the timeout aborts.
#
# An explicit DECLINE (Abort / closed window) aborts immediately — only
# an UNAVAILABLE xmessage falls through to the terminal fallback.

: "${DISPLAY:=localhost:0.0}"
export DISPLAY

PF=${POLYFRAMES_PATH:-$HOME/.local/bin/polyframes}

MSG='About to take over your live session

For a few moments the tests will:

  - switch your view to a scratch test tag
  - spawn real windows (Alacritty / Byobu)
  - split and rearrange frames, change layouts

Everything is cleaned up afterwards, but while it runs your session
is busy. An interrupted run may leave an empty tag behind
(merge manually: herbstclient merge_tag pf_integration_test).

Start the test suite now?'

# The suite needs a live WM; without one the run is pointless.
command -v herbstclient >/dev/null 2>&1 || {
    echo "live.guard: herbstclient not found" >&2
    exit 1
}
if [ "$(herbstclient attr tags.focus.name 2>/dev/null)" = "" ]; then
    echo "live.guard: no reachable hlwm on DISPLAY=$DISPLAY" >&2
    exit 1
fi

# Pick a LARGE font that the X server actually serves (guard against
# the tiny Athena default): first available of the candidates, or
# whatever $POLYFRAMES_GUARD_FONT forces.
choose_font() {
    if [ -n "$POLYFRAMES_GUARD_FONT" ]; then
        echo "$POLYFRAMES_GUARD_FONT"
        return 0
    fi
    for cf in \
        '-adobe-times-bold-r-normal--24-240-75-75-p-132-iso10646-1' \
        '-adobe-courier-bold-r-normal--24-240-75-75-m-150-iso10646-1' \
        '-adobe-courier-bold-o-normal--24-240-75-75-m-150-iso10646-1'
    do
    if xlsfonts 2>/dev/null | grep -Fq -- "$cf"; then
            echo "$cf"
            return 0
        fi
    done
    return 1
}

confirm_xmessage() {
    command -v xmessage >/dev/null 2>&1 || return 2 # absent → next strategy
    out=$(mktemp /tmp/polyframes-xmsg.XXXXXX)
    rm -f "$out"
    GF=$(choose_font)
    XMSG_OUT="$out" && export XMSG_OUT
    ARGS_FONT=""
    if [ -n "$GF" ]; then
        ARGS_FONT='-xrm|*font:|'"$GF"
    fi
    export XMSG_ARGS_FONT="$ARGS_FONT"
    export XMSG_MSG="$MSG"
    # The window-op wrapper must be a temp FILE, not `sh -c`: bunli's arg
    # parsing consumes flag-looking tokens (e.g. `-c`) even after `--`,
    # so the handoff passes `sh <file>` with strictly safe positionals.
    xwrap=$(mktemp /tmp/polyframes-xwrap.XXXXXX)
    {
        echo '#!/bin/sh'
        echo '# generated by live.guard.sh — xmessage confirmation wrapper'
        echo 'PFARGS=""'
        echo 'if [ -n "$XMSG_ARGS_FONT" ]; then'
        echo '    for tok in $(echo "$XMSG_ARGS_FONT" | tr "|" "\\n"); do'
        echo '        set -- "$@" "$tok"'
        echo '    done'
        echo 'fi'
        echo 'xmessage -center $PFARGS \'
        echo '    -buttons "Start:0,Abort:2" -default "Abort" \'
        echo '    "$XMSG_MSG" >"$XMSG_OUT" 2>/dev/null'
    } >"$xwrap"
    chmod +x "$xwrap"
    # The dialog floats + centers via `polyframes spawn --center`; its
    # exit status (the button value: Start=0, Abort=2) lands in the temp
    # file that we poll.
    "$PF" spawn --class Xmessage --center -- sh "$xwrap"
    rc=1
    i=0
    while [ "$i" -lt 300 ]; do # 5 min for slow readers
        if [ -s "$XMSG_OUT" ]; then
            stat=$(cat "$XMSG_OUT")
            [ "$stat" = "0" ] && rc=0
            break
        fi
        sleep 1
        i=$(( i + 1 ))
    done
    rm -f "$out" "$xwrap"
    [ "$rc" -eq 0 ]
}

confirm_terminal() {
    term=${TERMINAL:-}; command -v "${term:-alacritty}" >/dev/null 2>&1 \
        || term=alacritty
    command -v "$term" >/dev/null 2>&1 || return 1
    sentinel=$(mktemp /tmp/polyframes-live-confirm.XXXXXX)
    rm -f "$sentinel"
    # A floating prompt terminal (press-any-key), spawned through the
    # spawn module. The prompt is a SELF-CONTAINED shebang script (not
    # `-e sh -c ...`): bunli parses flag-like tokens even after `--`, so
    # a single safe positional avoids the whole class of bugs.
    termwrap=$(mktemp /tmp/polyframes-twrap.XXXXXX)
    {
        echo '#!/usr/bin/env bash'
        echo '# generated by live.guard.sh — live-test confirmation prompt'
        echo 'printf "%b\n" "$TERM_MSG"'
        echo 'printf "\nPress ANY key to BEGIN the suite now (or close this window to abort)..."'
        echo 'read -rsn1 _ && touch "$TERM_SENT"'
        echo 'exit 0'
    } >"$termwrap"
    chmod +x "$termwrap"
    TERM_SENT="$sentinel" && export TERM_SENT
    export TERM_MSG="$MSG"
    "$PF" spawn --class Alacritty --float on --focus -- "$termwrap"
    i=0
    while [ "$i" -lt 60 ]; do # 60s for slow readers
        [ -e "$sentinel" ] && {
            rm -f "$sentinel" "$termwrap"
            return 0
        }
        sleep 1
        i=$(( i + 1 ))
    done
    rm -f "$sentinel" "$termwrap"
    echo "live.guard: confirmation timed out" >&2
    return 1
}

if confirm_xmessage; then
    echo "live.guard: confirmed — starting the suite"
    exit 0
elif [ $? -eq 2 ]; then
    if confirm_terminal; then
        echo "live.guard: confirmed (terminal) — starting the suite"
        exit 0
    fi
fi
echo "live.guard: declined or not confirmable — nothing ran" >&2
exit 1
